#!/usr/bin/env python3
"""Make a one-phone embed of a locked board, for the linked prototype.

The prototype shows locked rooms by loading their board in an iframe, so the prototype and the
board can never drift apart. This copies the board and adds an embed mode:

  board.html?embed=1&look=paper|black

pins the first landing phone at 0,0 at 402x874, scale 1, over the rest of the board, with no status bar,
home bar or Tess word (the prototype draws its own), the room title in its ship name,
and the black look applied to that phone when look=black.

Usage (from docs/handoff/design-sheets):
  python3 ../session-oct25/scripts/make_embed.py money-indices-278/board.html prototype/purse.html
  python3 ../session-oct25/scripts/make_embed.py routines-garden-268/board.html prototype/watch.html
Re-run after any change to a locked board.
"""
import sys

CSS = """<style id="embed-css">
html.embed #ph1{position:fixed!important;left:0!important;top:0!important;z-index:2147483000!important;transform:none!important;border-radius:0!important}
html.embed .sbar,html.embed .home,html.embed .tessw{display:none!important}
</style>"""
# Note: the rest of the board stays laid out behind the pinned phone, on purpose. Hiding it (display:none) gives its
# canvases zero size, and the woodland's drawing loops never finish at width 0. overflow:hidden on html/body also hangs
# the woodland in headless Chromium; the prototype's iframe uses scrolling="no" instead.

JS = """<script id="embed-js">
(function(){var q=location.search;if(!/[?&]embed=1/.test(q))return;
 document.documentElement.classList.add('embed');
 var p=document.getElementById('ph1');if(!p)return;
 if(/[?&]look=black/.test(q))p.classList.add('black');
 var SHIP={Home:'Bridge',Notes:'Log',Weather:'Lookout',Training:'Deck',Kitchen:'Galley',Routines:'Watch',Money:'Purse'};
 var t=p.querySelector('.ttl');if(t&&SHIP[t.textContent.trim()])t.textContent=SHIP[t.textContent.trim()];
})();
</script>"""


def main(src, dst):
    s = open(src, encoding='utf-8').read()
    assert 'id="ph1"' in s, 'board has no #ph1 phone'
    # boards are written without <head>; put the embed CSS after the board's own styles so it wins
    j = s.index('</style>') + len('</style>')
    s = s[:j] + CSS + s[j:]
    # the embed script must run after the phones exist and before the board's own script builds
    # its canvases (they read .phone.black when they are made)
    i = s.index('<script>', s.index('id="ph1"'))
    s = s[:i] + JS + '\n' + s[i:]
    # boards are published inside the artifact skeleton; give the embed the same frame so it renders in standards mode
    head = ('<!doctype html>\n<!-- generated by session-oct25/scripts/make_embed.py from ' + src + '; edit the board, not this file -->\n'
            '<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
            '<style>:root{color-scheme:light}body{margin:0;font:14px system-ui,-apple-system,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>'
            '</head><body>\n')
    s = head + s + '\n</body></html>\n'
    open(dst, 'w', encoding='utf-8').write(s)
    print(dst, 'from', src)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
